// Generates the dotted southern-Africa map used behind the login page.
// Usage: node scripts/generate-map-dots.mjs <land-50m.json> src/components/ui/connectivityMapData.ts
// land-50m.json: https://cdn.jsdelivr.net/npm/world-atlas@2.0.2/land-50m.json
// Input: world-atlas land-50m TopoJSON (Natural Earth, public domain). Read as data only.
import { readFileSync, writeFileSync } from 'node:fs';

const [, , inputPath, outputPath] = process.argv;
const topo = JSON.parse(readFileSync(inputPath, 'utf8'));

// View: southern Africa (lon 0..50E, lat 10..36S)
const VIEW = { lonMin: 0, lonMax: 50, latMin: -36, latMax: -10, width: 1360 };
const lonSpan = VIEW.lonMax - VIEW.lonMin;
const latSpan = VIEW.latMax - VIEW.latMin;
const midLat = (VIEW.latMax + VIEW.latMin) / 2;
// Equirectangular with a cos(latitude) correction so shapes aren't stretched
VIEW.height = Math.round(VIEW.width * latSpan / (lonSpan * Math.cos(midLat * Math.PI / 180)));

// ── Decode TopoJSON arcs (quantized, delta-encoded) ──────────────────────────
const [sx, sy] = topo.transform.scale;
const [tx, ty] = topo.transform.translate;
const arcs = topo.arcs.map((arc) => {
  let x = 0, y = 0;
  return arc.map(([dx, dy]) => { x += dx; y += dy; return [x * sx + tx, y * sy + ty]; });
});
const arcCoords = (i) => (i >= 0 ? arcs[i] : arcs[~i].slice().reverse());
const ringFromArcs = (indices) => indices.flatMap((i, n) => (n === 0 ? arcCoords(i) : arcCoords(i).slice(1)));

const rings = [];
for (const geom of topo.objects.land.geometries) {
  const polygons = geom.type === 'Polygon' ? [geom.arcs] : geom.type === 'MultiPolygon' ? geom.arcs : [];
  for (const polygon of polygons) for (const ring of polygon) rings.push(ringFromArcs(ring));
}

// Keep only rings near the view (with margin) to speed up the point tests
const margin = 2;
const nearby = rings
  .map((ring) => {
    const xs = ring.map((p) => p[0]), ys = ring.map((p) => p[1]);
    return { ring, minX: Math.min(...xs), maxX: Math.max(...xs), minY: Math.min(...ys), maxY: Math.max(...ys) };
  })
  .filter((r) => r.maxX >= VIEW.lonMin - margin && r.minX <= VIEW.lonMax + margin
    && r.maxY >= VIEW.latMin - margin && r.minY <= VIEW.latMax + margin);

// Even-odd ray casting across all rings (holes such as Lesotho-in-SA don't exist in
// "land", and lakes are holes, so even-odd gives the right answer)
const onLand = (lon, lat) => {
  let inside = false;
  for (const { ring, minX, maxX, minY, maxY } of nearby) {
    if (lon < minX || lon > maxX || lat < minY || lat > maxY) continue;
    for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
      const [xi, yi] = ring[i], [xj, yj] = ring[j];
      if ((yi > lat) !== (yj > lat) && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside;
    }
  }
  return inside;
};

const project = (lon, lat) => [
  ((lon - VIEW.lonMin) / lonSpan) * VIEW.width,
  ((VIEW.latMax - lat) / latSpan) * VIEW.height,
];

// ── Staggered dot grid (every other row offset by half a step) ──────────────
const step = 0.42;
let d = '';
let count = 0;
for (let row = 0, lat = VIEW.latMax; lat >= VIEW.latMin; row++, lat -= step) {
  for (let lon = VIEW.lonMin + (row % 2 ? step / 2 : 0); lon <= VIEW.lonMax; lon += step) {
    if (!onLand(lon, lat)) continue;
    const [x, y] = project(lon, lat);
    d += `M${x.toFixed(1)} ${y.toFixed(1)}h0`; // zero-length segment + round caps = a dot
    count++;
  }
}

const out = `// Generated by generate-dots.mjs from Natural Earth land data (public domain).
// Do not edit by hand. View: lon ${VIEW.lonMin}..${VIEW.lonMax}, lat ${VIEW.latMin}..${VIEW.latMax}; ${count} dots.
export const MAP_VIEW = ${JSON.stringify(VIEW)} as const;

/** One SVG path: every dot is a zero-length segment drawn with round line caps. */
export const MAP_DOTS_PATH = '${d}';
`;
writeFileSync(outputPath, out);
console.log(`dots: ${count}, view: ${VIEW.width}x${VIEW.height}, bytes: ${out.length}`);
